fa_cfg_t fa_pick(enum ggml_metal_device_id device_id, int gpu_family, int dk, int dv, int64_t ne11, int64_t ne01, int64_t ne02, int64_t ne03) {
    if (g_fa_override_set) {
        return g_fa_override_cfg;
    }

    const fa_cfg_t baseline = { FA_Q_BASELINE, 0 };

    if (ne01 < FA_NE01_MIN) {
        return baseline;
    }

    // a last tile of 1..8 rows is padded with 8 more rows than baseline, costing 1/ceil(ne01/8)
    const int64_t ne01_last = ne01 % FA_Q_WIDE;
    if (ne01_last >= 1 && ne01_last <= FA_Q_BASELINE &&
        (ne01 + FA_Q_BASELINE - 1)/FA_Q_BASELINE < FA_NE01_MIN_PARTIAL_TILES) {
        return baseline;
    }

    const int64_t tiles = ((ne01 + FA_Q_WIDE - 1)/FA_Q_WIDE)*ne02*ne03;

    fa_key_t k{};
    k.dk = (int16_t) dk;
    k.dv = (int16_t) dv;

    auto lookup = [&](enum ggml_metal_device_id dev) -> const fa_entry_t * {
        k.device_id = (int8_t) dev;
        for (const int8_t ne11_b : { (int8_t) fa_ne11_bucket(ne11), FA_NE11_DEFAULT }) {
            k.ne11_b = ne11_b;
            for (const auto & e : fa_tuned_table) {
                if (memcmp(&e.key, &k, sizeof(k)) == 0) {
                    return &e;
                }
            }
        }
        return nullptr;
    };

    if (const auto * e = lookup(device_id)) {
        return tiles >= e->tiles_min ? e->cfg : baseline;
    }

    if (gpu_family > 0) {
        const enum ggml_metal_device_id rep = fa_vec_family_representative(gpu_family);
        if (rep != GGML_METAL_DEVICE_GENERIC) {
            if (const auto * e = lookup(rep)) {
                return tiles >= e->tiles_min ? e->cfg : baseline;
            }
        }
    }

    return baseline;
}


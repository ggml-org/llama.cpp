#!/usr/bin/env python3
"""Emit the Unicode category ranges the tokenizer's split pattern needs.

Tokenizer.java compiles a GPT-4 style pattern that leans on Java's \\p{L},
\\p{N} and \\p{Z}. Pulling ICU into the native engine just for those three
classes would be a megabyte of tables for one bit test, so the ranges are
baked here instead and checked into the tree as a plain C++ header.

    python3 gen_unicode_tables.py > unicode_tables.h
"""

import sys
import unicodedata

MAX_CP = 0x110000


def classify(code: str) -> int:
    if code in ("Lu", "Ll", "Lt", "Lm", "Lo"):
        return 1  # letter
    if code in ("Nd", "Nl", "No"):
        return 2  # number
    if code in ("Zs", "Zl", "Zp"):
        return 4  # separator
    return 0


def ranges(mask: int):
    out = []
    start = None
    for cp in range(MAX_CP):
        if 0xD800 <= cp <= 0xDFFF:  # surrogates are not scalar values
            hit = 0
        else:
            hit = classify(unicodedata.category(chr(cp)))
        if hit & mask:
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def emit(name: str, table) -> None:
    print(f"static const CharRange {name}[] = {{")
    for i in range(0, len(table), 4):
        chunk = ", ".join(f"{{0x{lo:05X}, 0x{hi:05X}}}" for lo, hi in table[i:i + 4])
        print("    " + chunk + ",")
    print("};")
    print(f"static const size_t {name}_count = sizeof({name}) / sizeof({name}[0]);")
    print()


def main() -> None:
    letters = ranges(1)
    numbers = ranges(2)
    separators = ranges(4)
    print("// Generated by gen_unicode_tables.py from Unicode %s. Do not edit." % unicodedata.unidata_version)
    print("#pragma once")
    print()
    print("#include <cstddef>")
    print("#include <cstdint>")
    print()
    print("namespace m5 {")
    print("namespace unicode {")
    print()
    print("struct CharRange { uint32_t lo, hi; };")
    print()
    emit("kLetters", letters)
    emit("kNumbers", numbers)
    emit("kSeparators", separators)
    print("}  // namespace unicode")
    print("}  // namespace m5")
    print(
        f"// categories: letters={len(letters)} numbers={len(numbers)} separators={len(separators)}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()

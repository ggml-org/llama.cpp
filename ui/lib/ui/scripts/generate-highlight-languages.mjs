// Writes src/lib/utils/highlight-languages.ts: one loader per highlight.js language lowlight ships (each its own chunk
// in an app's build), the aliases that name them, and lowlight's common languages, which auto-detection picks from.
// Run it after updating highlight.js or lowlight: node scripts/generate-highlight-languages.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import hljs from "highlight.js/lib/core";
import { all, common } from "lowlight";

const OUTPUT = new URL(
  "../src/lib/utils/highlight-languages.ts",
  import.meta.url,
);

const names = Object.keys(all).sort();
const aliases = {};
const subLanguages = {};

// the languages a definition embeds (`subLanguage`: CSS and JavaScript inside HTML, say), which highlight.js leaves
// plain unless they are registered too
function collectSubLanguages(mode, found, seen = new Set()) {
  if (!mode || typeof mode !== "object" || seen.has(mode)) return found;

  seen.add(mode);

  for (const sub of [mode.subLanguage ?? []].flat())
    found.add(sub.toLowerCase());

  for (const value of Object.values(mode)) {
    if (Array.isArray(value))
      for (const item of value) collectSubLanguages(item, found, seen);
    else if (value && typeof value === "object")
      collectSubLanguages(value, found, seen);
  }

  return found;
}

// register in lowlight's order, so an alias two languages claim names the same one it does in lowlight
for (const name of names) {
  const highlighter = hljs.newInstance();

  highlighter.registerLanguage(name, all[name]);

  for (const alias of highlighter.getLanguage(name)?.aliases ?? []) {
    const key = alias.toLowerCase();

    if (key !== name && !(key in all)) aliases[key] = name;
  }
}

for (const name of names) {
  const definition = all[name](hljs);
  const found = [...collectSubLanguages(definition, new Set())]
    .map((sub) => (sub in all ? sub : aliases[sub]))
    .filter((sub) => sub && sub !== name);

  if (found.length) subLanguages[name] = [...new Set(found)].sort();
}

const quote = (s) => `'${s}'`;
const key = (s) => (/^[a-z_$][\w$]*$/i.test(s) ? s : quote(s));

const source = `// Generated by scripts/generate-highlight-languages.mjs from lowlight's languages; do not edit by hand.
import type { LanguageFn } from 'highlight.js';

/** Loads one highlight.js language, by its name. */
export const HIGHLIGHT_LANGUAGE_LOADERS: Record<string, () => Promise<{ default: LanguageFn }>> = {
${names.map((n) => `\t${key(n)}: () => import('highlight.js/lib/languages/${n}')`).join(",\n")}
};

/** The language each alias names (\`js\` -> \`javascript\`), as highlight.js resolves it. */
export const HIGHLIGHT_LANGUAGE_ALIASES: Record<string, string> = {
${Object.keys(aliases)
  .sort()
  .map((a) => `\t${key(a)}: ${quote(aliases[a])}`)
  .join(",\n")}
};

/** The languages each language embeds, to load with it so its embedded code is highlighted too. */
export const HIGHLIGHT_SUB_LANGUAGES: Record<string, readonly string[]> = {
${Object.keys(subLanguages)
  .map((n) => `\t${key(n)}: [${subLanguages[n].map(quote).join(", ")}]`)
  .join(",\n")}
};

/** lowlight's common languages: the ones auto-detection picks from. */
export const HIGHLIGHT_AUTO_DETECT_LANGUAGES: readonly string[] = [
${Object.keys(common)
  .sort()
  .map((n) => `\t${quote(n)}`)
  .join(",\n")}
];
`;

writeFileSync(OUTPUT, source);
execFileSync("npx", ["prettier", "--write", OUTPUT.pathname], {
  stdio: "inherit",
});

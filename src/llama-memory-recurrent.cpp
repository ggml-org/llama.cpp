llama_memory_recurrent::llama_memory_recurrent(
        const llama_model & model,
                ggml_type   type_r,
                ggml_type   type_s,
                     bool   offload,
                 uint32_t   mem_size,
                 uint32_t   n_seq_max,
                 uint32_t   n_rs_seq,
    const layer_filter_cb & filter, bool stream_host_spill) : hparams(model.hparams), n_seq_max(n_seq_max) {
    const int32_t n_layer = hparams.n_layer();

    head = 0;
    size = mem_size;
    used = 0;

    this->n_rs_seq = n_rs_seq;
    rs_idx.assign(n_seq_max, 0);
    const char * spill_flag=std::getenv("LLAMA_RS_HOST_SPILL");
    const bool want_spill = n_rs_seq && (stream_host_spill || (spill_flag && std::strcmp(spill_flag,"1") == 0));
    uint32_t publication_slots=2;
    if (stream_host_spill) {
        llama_recurrent_rollback_plan plan;
        if (!llama_recurrent_rollback_plan_make(n_rs_seq,false,n_rs_seq < 8 ? n_rs_seq+1 : 0,plan))
            throw std::runtime_error("invalid streamed recurrent rollback plan");
        publication_slots=plan.stage_slots;
    }
    if (want_spill && hparams.ple_conv_state() > 0) throw std::runtime_error("recurrent host spill does not support PLE history");
    if (want_spill && n_seq_max != 1) throw std::runtime_error("recurrent host spill requires one serial sequence");


    cells.clear();
    cells.resize(mem_size);

    // define a comparator for the buft -> ctx map to ensure that the order is well-defined:
    struct ggml_backend_buft_comparator {
        bool operator()(const ggml_backend_buffer_type_t & lhs, const ggml_backend_buffer_type_t & rhs) const {
            return strcmp(ggml_backend_buft_name(lhs), ggml_backend_buft_name(rhs)) < 0;
        }
    };
    std::map<ggml_backend_buffer_type_t, ggml_context_ptr, ggml_backend_buft_comparator> ctx_map;

    // create a context for each buffer type
    auto ctx_for_buft = [&](ggml_backend_buffer_type_t buft) -> ggml_context * {
        auto it = ctx_map.find(buft);
        if (it == ctx_map.end()) {
            ggml_init_params params = {
                // r and s per layer, plus the separate PLE conv row where the model has one
                /*.mem_size   =*/ size_t((hparams.ple_conv_state() > 0 ? 3u : 2u)*n_layer*ggml_tensor_overhead()),
                /*.mem_buffer =*/ NULL,
                /*.no_alloc   =*/ true,
            };

            ggml_context * ctx = ggml_init(params);
            if (!ctx) {
                return nullptr;
            }

            ctx_map.emplace(buft, ctx);

            return ctx;
        }

        return it->second.get();
    };

    r_l.resize(n_layer);
    s_l.resize(n_layer);
    p_l.resize(n_layer);

    for (int i = 0; i < n_layer; i++) {
        if (filter && !filter(i)) {
            LLAMA_LOG_DEBUG("%s: layer %3d: skipped\n", __func__, i);
            continue;
        }

        const char * dev_name = "CPU";

        ggml_backend_buffer_type_t buft = ggml_backend_cpu_buffer_type();

        if (offload) {
            auto * dev = model.dev_layer(i);
            buft = ggml_backend_dev_buffer_type(dev);

            dev_name = ggml_backend_dev_name(dev);
        }

        LLAMA_LOG_DEBUG("%s, layer %3d: dev = %s\n", __func__, i, dev_name);

        ggml_context * ctx = ctx_for_buft(buft);
        if (!ctx) {
            throw std::runtime_error("failed to create ggml context for rs cache");
        }

        const uint32_t n_rows = mem_size * (want_spill ? 1 : (1 + n_rs_seq));
        ggml_tensor * r = ggml_new_tensor_2d(ctx, type_r, hparams.n_embd_r(), n_rows);
        ggml_tensor * s = ggml_new_tensor_2d(ctx, type_s, hparams.n_embd_s(), n_rows);
        ggml_format_name(r, "cache_r_l%d", i);
        ggml_format_name(s, "cache_s_l%d", i);
        r_l[i] = r;
        s_l[i] = s;

        // the PLE history needs its own row: Meta must mirror it while the delta-net conv state next door stays split
        if (hparams.ple_conv_state() > 0 && hparams.is_ple(i)) {
            ggml_tensor * p = ggml_new_tensor_2d(ctx, type_r, hparams.ple_conv_state(), n_rows);
            ggml_format_name(p, "cache_ple_r_l%d", i);
            p_l[i] = p;
        }
    }

    // allocate tensors and initialize the buffers to avoid NaNs in the padding
    for (auto & [buft, ctx] : ctx_map) {
        ggml_backend_buffer_t buf = ggml_backend_alloc_ctx_tensors_from_buft(ctx.get(), buft);
        if (!buf) {
            throw std::runtime_error("failed to allocate buffer for rs cache");
        }
        ggml_backend_buffer_clear(buf, 0);
        LLAMA_LOG_INFO("%s: %10s RS buffer size = %8.2f MiB\n", __func__, ggml_backend_buffer_name(buf), ggml_backend_buffer_get_size(buf)/1024.0/1024.0);
        ctxs_bufs.emplace_back(std::move(ctx), buf);
    }

    if (is_empty()) {
        if (n_rs_seq > 0) {
            this->n_rs_seq = 0;
            LLAMA_LOG_INFO("%s: disabling rollback snapshots because the memory module is empty\n", __func__);
        }
    }

    if (want_spill && !is_empty()) {
        std::vector<llama_recurrent_spill_layer> specs(r_l.size());
        ggml_backend_dev_t device=nullptr;
        for (size_t i=0;i<r_l.size();++i) {
            if (!r_l[i]) continue;
            if (!s_l[i]) throw std::runtime_error("incomplete recurrent layer storage");
            specs[i]={r_l[i]->type,s_l[i]->type,uint64_t(r_l[i]->ne[0]),uint64_t(s_l[i]->ne[0]),true};
            if (offload) {
                auto * layer_device=model.dev_layer(int(i));
                if (device && device != layer_device) throw std::runtime_error("recurrent spill requires one device");
                device=layer_device;
            }
        }
        llama_recurrent_spill_layout layout;
        if (!llama_recurrent_spill_layout_make(specs,mem_size,n_rs_seq,layout))
            throw std::runtime_error("invalid recurrent spill layout");
        auto * host_type=device ? ggml_backend_dev_host_buffer_type(device) : nullptr;
        if (!host_type) host_type=ggml_backend_cpu_buffer_type();
        spill_cache_id=next_spill_cache_id.fetch_add(1,std::memory_order_relaxed);
        spill=llama_recurrent_spill_bank::create(layout,host_type,spill_cache_id,0);
        if (!spill) {
            LLAMA_LOG_ERROR("%s: host recurrent snapshot allocation failed: buft=%s, bytes=%zu, cells=%u, depth=%u\n",
                    __func__, host_type ? ggml_backend_buft_name(host_type) : "null", layout.host_snapshot_bytes, mem_size, n_rs_seq);
            throw std::runtime_error("failed to allocate pinned recurrent snapshots");
        }
        const char * staged=std::getenv("LLAMA_RS_STAGED_PUBLICATION");
        if (stream_host_spill || (staged && std::strcmp(staged,"1") == 0)) {
            auto * stage_device=device ? device : ggml_backend_dev_by_name("CPU");
            auto * stage_type=recurrent_stage_type(stage_device);
            if (!stage_type || !spill->enable_publication(stage_device,stage_type,publication_slots)) {
                throw std::runtime_error("failed to create recurrent publication stage");
            }
            LLAMA_LOG_INFO("%s: %s RS publication stage size = %.2f MiB\n",__func__,
                ggml_backend_buft_name(stage_type),double(spill->staged_device_bytes())/(1024.0*1024.0));
        }
    }

    {
        const size_t memory_size_r = size_r_bytes();
        const size_t memory_size_s = size_s_bytes();
        const size_t memory_size_p = size_p_bytes();

        LLAMA_LOG_INFO("%s: size = %7.2f MiB (%6u cells, %3d layers, %2u seqs %2u rs_seq), R (%s): %7.2f MiB, S (%s): %7.2f MiB, P (%s): %7.2f MiB\n", __func__,
                (float)(memory_size_r + memory_size_s + memory_size_p) / (1024.0f * 1024.0f), mem_size, n_layer, n_seq_max, n_rs_seq,
                ggml_type_name(type_r), (float)memory_size_r / (1024.0f * 1024.0f),
                ggml_type_name(type_s), (float)memory_size_s / (1024.0f * 1024.0f),
                ggml_type_name(type_r), (float)memory_size_p / (1024.0f * 1024.0f));
    }
}

void llama_memory_recurrent::clear(bool data) {
    if (spill) {
        spill->reset(data);
        spill_pending=false;
        spill_restore_pending=false;
    }

    for (int32_t i = 0; i < (int32_t) size; ++i) {
        cells[i].pos = -1;
        cells[i].seq_id.clear();
        cells[i].src = -1;
        cells[i].tail = -1;
    }

    head = 0;
    used = 0;

    if (data) {
        for (auto & [_, buf] : ctxs_bufs) {
            ggml_backend_buffer_clear(buf.get(), 0);
        }
    }

    std::fill(rs_idx.begin(), rs_idx.end(), 0);
}

bool llama_memory_recurrent::seq_rm(llama_seq_id seq_id, llama_pos p0, llama_pos p1) {
    uint32_t new_head = size;

    if (p0 < 0) {
        p0 = 0;
    }

    if (p1 < 0) {
        p1 = std::numeric_limits<llama_pos>::max();
    }

    if (seq_id >= 0 && (uint32_t) seq_id >= this->n_seq_max) {
        LLAMA_LOG_ERROR("%s: invalid seq_id (%d) - larger than n_seq_max (%d)\n", __func__, seq_id, this->n_seq_max);
        return false;
    }

    const bool rm_all = p0 == 0 && p1 == std::numeric_limits<llama_pos>::max();
    if (rm_all) {
        if (spill) {
            spill->reset(false);
            spill_pending=false;
            spill_restore_pending=false;
        }
        if (seq_id >= 0) {
            set_rs_idx(seq_id, 0);
        } else {
            std::fill(rs_idx.begin(), rs_idx.end(), 0);
        }
    }

    // models like Mamba or RWKV can't have a state partially erased at the end
    // of the sequence because their state isn't preserved for previous tokens
    if (seq_id >= (int64_t) size) {
        // could be fatal
        return false;
    }
    if (0 <= seq_id) {
        int32_t & tail_id = cells[seq_id].tail;
        if (tail_id >= 0) {
            auto & cell = cells[tail_id];

            // partial rollback via per-token snapshot index (bounded by n_rs_seq)
            if (0 < p0 && p0 <= cell.pos && p1 > cell.pos) {
                // a cell shared by several sequences cannot move back for only one of them
                if (cell.seq_id.size() > 1) {
                    return false;
                }
                // the filter kept no layer (e.g. an MTP draft context), so only the position moves back
                if (is_empty()) {
                    cell.pos = p0 - 1;
                    return true;
                }
                const llama_pos rollback = cell.pos - (p0 - 1);
                // pending rollback is single-use
                const bool pending = rs_idx[seq_id] != 0;
                if (!pending && rollback >= 1 && rollback <= (llama_pos) n_rs_seq) {
                    if (spill && !spill_slot_valid(uint32_t(rollback))) return false;
                    set_rs_idx(seq_id, (uint32_t) rollback);
                    cell.pos = p0 - 1;
                    return true;
                }
                return false;
            }
            // invalidate tails which will be cleared
            if (p0 <= cell.pos && cell.pos < p1) {
                tail_id = -1;
            }
        }
    } else {
        // seq_id is negative, then the range should include everything or nothing
        if (p0 != p1 && (p0 != 0 || p1 != std::numeric_limits<llama_pos>::max())) {
            //printf("[DEBUG] inside `llama_memory_recurrent::seq_rm`: `seq_id` is negative, so returning false\n");
            return false;
        }
    }

    for (uint32_t i = 0; i < size; ++i) {
        if (cells[i].pos >= p0 && cells[i].pos < p1) {
            if (seq_id < 0) {
                cells[i].seq_id.clear();
            } else if (cells[i].has_seq_id(seq_id)) {
                cells[i].seq_id.erase(seq_id);
            } else {
                continue;
            }
            if (cells[i].is_empty()) {
                // keep count of the number of used cells
                if (cells[i].pos >= 0) {
                    used--;
                }
                cells[i].pos = -1;
                cells[i].src = -1;
                if (new_head == size) {
                    new_head = i;
                }
            }
        }
    }

    // If we freed up a slot, set head to it so searching can start there.
    if (new_head != size && new_head < head) {
        head = new_head;
    }

    return true;
}

void llama_memory_recurrent::seq_cp(llama_seq_id seq_id_src, llama_seq_id seq_id_dst, llama_pos p0, llama_pos p1) {
    if (seq_id_src == seq_id_dst) {
        return;
    }

    if (p0 < 0) {
        p0 = 0;
    }

    if (p1 < 0) {
        p1 = std::numeric_limits<llama_pos>::max();
    }

    if ((uint32_t) seq_id_dst < size && (uint32_t) seq_id_src < size) {
        auto & tail_src = cells[seq_id_src];
        auto & tail_dst = cells[seq_id_dst];
        if (tail_dst.tail >= 0) {
            // clear destination seq_id if it wasn't empty
            auto & cell_dst = cells[tail_dst.tail];

            cell_dst.seq_id.erase(seq_id_dst);
            tail_dst.tail = -1;
            if (cell_dst.seq_id.empty()) {
                cell_dst.pos = -1;
                cell_dst.src = -1;
                used -= 1;
            }
        }
        if (tail_src.tail >= 0) {
            auto & cell_src = cells[tail_src.tail];

            cell_src.seq_id.insert(seq_id_dst);
            tail_dst.tail = tail_src.tail;
        }
    }
}

void llama_memory_recurrent::seq_keep(llama_seq_id seq_id) {
    uint32_t new_head = size;

    for (uint32_t i = 0; i < size; ++i) {
        if ((llama_seq_id) i != seq_id) {
            cells[i].tail = -1;
        }

        if (!cells[i].has_seq_id(seq_id)) {
            if (cells[i].pos >= 0) {
                used--;
            }

            cells[i].pos = -1;
            cells[i].src = -1;
            cells[i].seq_id.clear();

            if (new_head == size){
                new_head = i;
            }
        } else {
            cells[i].seq_id.clear();
            cells[i].seq_id.insert(seq_id);
        }
    }

    // If we freed up a slot, set head to it so searching can start there.
    if (new_head != size && new_head < head) {
        head = new_head;
    }
}

void llama_memory_recurrent::seq_add(llama_seq_id seq_id, llama_pos p0, llama_pos p1, llama_pos shift) {
    if (shift == 0) {
        return;
    }

    if (p0 < 0) {
        p0 = 0;
    }

    if (p1 < 0) {
        p1 = std::numeric_limits<llama_pos>::max();
    }

    // If there is no range then return early to avoid looping over the
    if (p0 == p1) {
        return;
    }

    // for Mamba-like or RWKV models, only the pos needs to be shifted
    if (0 <= seq_id && seq_id < (int64_t) size) {
        const int32_t tail_id = cells[seq_id].tail;
        if (tail_id >= 0) {
            auto & cell = cells[tail_id];
            if (cell.has_seq_id(seq_id) && p0 <= cell.pos && cell.pos < p1) {
                cell.pos += shift;
            }
        }
    }
}

void llama_memory_recurrent::seq_div(llama_seq_id seq_id, llama_pos p0, llama_pos p1, int d) {
    if (d == 1) {
        return;
    }

    if (p0 < 0) {
        p0 = 0;
    }

    if (p1 < 0) {
        p1 = std::numeric_limits<llama_pos>::max();
    }

    // If there is no range then return early to avoid looping over the cache.
    if (p0 == p1) {
        return;
    }

    // for Mamba-like or RWKV models, only the pos needs to be changed
    if (0 <= seq_id && seq_id < (int64_t) size) {
        const int32_t tail_id = cells[seq_id].tail;
        if (tail_id >= 0) {
            auto & cell = cells[tail_id];
            if (cell.has_seq_id(seq_id) && p0 <= cell.pos && cell.pos < p1) {
                cell.pos /= d;
            }
        }
    }
}

llama_pos llama_memory_recurrent::seq_pos_min(llama_seq_id seq_id) const {
    llama_pos result = std::numeric_limits<llama_pos>::max();

    for (uint32_t i = 0; i < size; ++i) {
        if (cells[i].has_seq_id(seq_id)) {
            result = std::min(result, cells[i].pos);
        }
    }

    if (result == std::numeric_limits<llama_pos>::max()) {
        result = -1;
    }

    return result;
}

llama_pos llama_memory_recurrent::seq_pos_max(llama_seq_id seq_id) const {
    llama_pos result = -1;

    for (uint32_t i = 0; i < size; ++i) {
        if (cells[i].has_seq_id(seq_id)) {
            result = std::max(result, cells[i].pos);
        }
    }

    return result;
}

void llama_memory_recurrent::set_rs_idx(llama_seq_id seq_id, uint32_t idx) {
    if (seq_id < 0) {
        std::fill(rs_idx.begin(), rs_idx.end(), 0);
        return;
    }

    assert(n_seq_max == rs_idx.size());

    GGML_ASSERT((uint32_t) seq_id < n_seq_max);
    GGML_ASSERT(idx <= n_rs_seq);

    rs_idx[seq_id] = idx;
}

std::map<ggml_backend_buffer_type_t, size_t> llama_memory_recurrent::memory_breakdown() const {
    std::map<ggml_backend_buffer_type_t, size_t> ret;
    for (const auto & [_, buf] : ctxs_bufs) {
        ret[ggml_backend_buffer_get_type(buf.get())] += ggml_backend_buffer_get_size(buf.get());
    }
    return ret;
}

bool llama_memory_recurrent::spill_slot_valid(uint32_t slot) {
    if (!spill || !complete_spill() || !spill_epoch || slot == 0 || slot > n_rs_seq) return false;
    bool found=false;
    for (size_t layer=0;layer<r_l.size();++layer) {
        if (!r_l[layer]) continue;
        found=true;
        for (bool value : {false,true}) {
            const auto generation=spill->snapshot_generation(layer,value,slot);
            if (generation) {
                if (!spill->snapshot_data(layer,value,slot,generation)) return false;
            } else if (!spill->snapshot_pristine(layer,value,slot)) {
                return false;
            }
        }
    }
    return found;
}

bool llama_memory_recurrent::restore_spill_slot(uint32_t slot) {
    if (!spill || !complete_spill() || !spill_epoch || slot == 0 || slot > n_rs_seq) return false;
    struct pending_restore { ggml_tensor * tensor; const void * data; };
    std::vector<pending_restore> rows;
    rows.reserve(2*r_l.size());
    size_t largest=0;
    for (size_t layer=0;layer<r_l.size();++layer) {
        if (!r_l[layer]) continue;
        for (bool value : {false,true}) {
            auto * tensor=value ? s_l[layer] : r_l[layer];
            if (!tensor) return false;
            const auto generation=spill->snapshot_generation(layer,value,slot);
            if (!generation && !spill->snapshot_pristine(layer,value,slot)) return false;
            const auto * data=generation ? spill->snapshot_data(layer,value,slot,generation) : nullptr;
            if (generation && !data) return false;
            largest=std::max(largest,ggml_nbytes(tensor));
            rows.push_back({tensor,data});
        }
    }
    if (rows.empty()) return false;
    // This conservative boundary keeps checkpoint/state APIs valid before the next graph uses slot 0.
    std::vector<uint8_t> zero(largest,0);
    for (const auto & row : rows) ggml_backend_tensor_set(row.tensor,row.data ? row.data : zero.data(),0,ggml_nbytes(row.tensor));
    return true;
}


bool llama_memory_recurrent::spill_enabled() const noexcept { return bool(spill); }

bool llama_memory_recurrent::complete_spill() {
    if (!spill_pending) return true;
    if (!spill || !spill->complete_capture()) return false;
    spill_pending=false;
    return true;
}

bool llama_memory_recurrent::restore_spill_async(ggml_backend_sched_t sched) {
    if (!spill || rs_idx.empty() || rs_idx[0] == 0) return true;
    if (!sched || spill_restore_pending) return false;
    const uint32_t slot=rs_idx[0];
    if (!spill_slot_valid(slot) || !spill->begin_restore({spill_cache_id,0,spill_epoch},slot)) return false;
    for (size_t layer=0;layer<r_l.size();++layer) {
        if (!r_l[layer]) continue;
        for (bool value : {false,true}) {
            auto * tensor=value ? s_l[layer] : r_l[layer];
            auto * backend=ggml_backend_sched_get_tensor_backend(sched,tensor);
            if (!backend || !spill->restore(backend,layer,value,tensor,0)) {
                spill->cancel();
                return false;
            }
        }
    }
    if (!spill->publish_restore()) {
        spill->cancel();
        return false;
    }
    spill_restore_pending=true;
    set_rs_idx(0,0);
    return true;
}

bool llama_memory_recurrent::complete_restore_spill() {
    if (!spill_restore_pending) return true;
    if (!spill || !spill->complete_restore()) return false;
    spill_restore_pending=false;
    return true;
}

bool llama_memory_recurrent::materialize_spill_for_device_state() {
    if (!spill || rs_idx.empty() || rs_idx[0] == 0) return true;
    if (!complete_restore_spill() || !restore_spill_slot(rs_idx[0])) return false;
    set_rs_idx(0,0);
    return true;
}

bool llama_memory_recurrent::staged_publication_enabled() const noexcept {
    return spill && spill->staged_publication_enabled();
}

bool llama_memory_recurrent::begin_spill_capture(uint32_t tokens) {
    if (!staged_publication_enabled()) return true;
    if (!complete_spill() || !complete_restore_spill() || spill_epoch == UINT64_MAX) return false;
    return spill->begin_staged_capture({spill_cache_id,0,spill_epoch+1},tokens);
}

void llama_memory_recurrent::abort_spill_capture() noexcept {
    if (staged_publication_enabled()) spill->cancel();
}

bool llama_memory_recurrent::capture_spill(ggml_backend_sched_t sched,
        const std::vector<llm_graph_recurrent_snapshot> & outputs) {
    if (!spill) return true;
    if (staged_publication_enabled()) {
        if (!sched || outputs.empty() || spill_epoch == UINT64_MAX || !spill->publish_capture()) return false;
        ++spill_epoch;
        spill_pending=true;
        return true;
    }

    if (!sched || outputs.empty() || !complete_spill() || spill_epoch == UINT64_MAX) return false;
    const uint64_t next=spill_epoch+1;
    if (!spill->begin_capture({spill_cache_id,0,next})) return false;
    for (const auto & output : outputs) {
        auto * backend=output.tensor ? ggml_backend_sched_get_tensor_backend(sched,output.tensor) : nullptr;
        if (!backend || !spill->capture(backend,output.layer,output.value,output.slot,
                output.tensor,output.offset)) {
            spill->cancel();
            return false;
        }
    }
    if (!spill->publish_capture()) { spill->cancel(); return false; }
    spill_epoch=next;
    spill_pending=true;
    return true;
}

